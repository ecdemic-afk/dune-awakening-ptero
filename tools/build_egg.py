def build() -> dict:
    with open(os.path.join(ROOT, "egg", "install.sh"), encoding="utf-8") as fh:
        script = fh.read()
    return {
        "_comment": "Dune: Awakening for Pterodactyl — generated by tools/build_egg.py; edit that, not this.",
        "meta": {"version": "PTDL_v2", "update_url": None},
        "exported_at": "2026-10-21T00:00:00+00:00",
        "name": "Dune: Awakening",
        "author": "ecdemic-afk@users.noreply.github.com",
        "description": ("Dune: Awakening dedicated server (full battlegroup) on Pterodactyl. One port block, "
                        "one config file (config/dune.toml), in-place game updates and restarts, health checks "
                        "and Discord alerts."),
        "features": ["steam_disk_space"],
        "docker_images": {"Dune Awakening": IMAGE},
        "file_denylist": [],
        "startup": "python3 /home/container/runtime/dunectl.py run",
        "config": {
            "files": "{}",
            "startup": json.dumps({"done": "[dune] READY"}),
            "logs": "{}",
            "stop": "stop",
        },
        "scripts": {"installation": {"script": script,
                                     "container": "ghcr.io/parkervcp/installers:debian",
                                     "entrypoint": "bash"}},
        "variables": [
            {"name": name, "description": desc, "env_variable": env, "default_value": default,
             "user_viewable": True, "user_editable": True, "rules": rules, "field_type": "text"}
            for name, env, default, desc, rules in VARIABLES
        ],
    }


def main() -> int:
    egg = build()
    for v in egg["variables"]:
        for rule in v["rules"].split("|"):
            if not rule:
                print(f"empty rule in {v['env_variable']}", file=sys.stderr)
                return 1
    out = os.path.join(ROOT, "egg", "egg-dune-awakening.json")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(egg, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"wrote {os.path.relpath(out, ROOT)} ({len(egg['variables'])} variables)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
