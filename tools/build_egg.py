#!/usr/bin/env python3
"""Build egg/egg-dune-awakening.json (Pterodactyl PTDL_v2) from egg/install.sh.

    python tools/build_egg.py

The install script and the variable list live here in readable form; the egg
JSON is generated so the two can never drift apart. Pterodactyl stores each
variable's rules as one pipe-separated string, so no rule may contain '|'.
"""
